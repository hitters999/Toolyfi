// Toolyfi — Gemini Tool Research Agent
// Writes ONLY to research-queue.md. Never touches live tool pages, never publishes HTML.

const fs = require('fs');
const path = require('path');

const API_KEY = process.env.GEMINI_API_KEY;
const MODEL = 'gemini-2.0-flash'; // update if a newer flash/pro model is preferred
const OUTPUT_FILE = path.join(process.cwd(), 'research-queue.md');

// Existing Toolyfi tools (keep in sync with master file Section 5)
const EXISTING_TOOLS = [
  'qr-code-generator', 'image-resizer', 'image-compressor', 'base64-encoder',
  'password-generator', 'link-shortener', 'age-calculator', 'bmi-calculator',
  'currency-converter', 'word-counter', 'loan-calculator', 'json-formatter',
  'csv-to-json', 'invoice-generator', 'resume-builder', 'tip-calculator',
  'number-to-words', 'scientific-calculator', 'ai-prompt-generator',
  'ai-tool-recommender', 'html-live-preview', 'state-tax-refund-tracker',
  'unit-converter', 'temperature-converter', 'cgpa-to-percentage',
  'markdown-to-html-seo', 'youtube-transcript-extractor'
];

const PROMPT = `
You are an SEO + product researcher for Toolyfi.com, a free single-page web-tools
platform (calculators, converters, generators — all client-side, no signup).

Goal: find 6 NEW tool ideas that fit these strict filters:
1. LOW domain-rating competition — top-ranking pages for the keyword should mostly be
   thin, ad-heavy, or low-quality sites, NOT high-authority sites like Omni Calculator,
   RapidTables, CalculatorSoup, or major brands.
2. LOW keyword competition — decent monthly search interest but not a saturated
   "everyone already built this" tool.
3. Must be buildable as a single-file client-side HTML/CSS/JS tool (no backend, no
   paid API dependency for the core function).
4. Must NOT duplicate or overlap with this existing Toolyfi tool list:
   ${EXISTING_TOOLS.join(', ')}

For each of the 6 ideas, return STRICT JSON (no markdown, no prose outside JSON) as an
array of objects with these exact keys:
{
  "tool_name": string,
  "slug": string (kebab-case),
  "primary_keyword": string,
  "search_volume_estimate": string (e.g. "500-1k/mo"),
  "competition_estimate": "Low" | "Low-Medium",
  "top_competitor": string (site name),
  "competitor_gap": string (1 sentence — what's weak about their page),
  "unique_angle": string (1-2 sentences — the specific differentiator Toolyfi should build that competitors don't have, similar in spirit to how state-tax-refund-tracker added an IRS Cycle Code Decoder),
  "difficulty": "Easy" | "Medium"
}

Return ONLY the JSON array.
`;

async function callGemini() {
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${MODEL}:generateContent?key=${API_KEY}`;
  const res = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      contents: [{ parts: [{ text: PROMPT }] }],
      generationConfig: { temperature: 0.7 }
    })
  });

  if (!res.ok) {
    const errText = await res.text();
    throw new Error(`Gemini API error ${res.status}: ${errText}`);
  }

  const data = await res.json();
  const text = data.candidates?.[0]?.content?.parts?.[0]?.text || '';
  const cleaned = text.replace(/```json|```/g, '').trim();
  return JSON.parse(cleaned);
}

function formatEntry(item, index) {
  return `
### ${index + 1}. ${item.tool_name}
- **Slug:** \`${item.slug}\`
- **Primary keyword:** ${item.primary_keyword}
- **Search volume (est.):** ${item.search_volume_estimate}
- **Competition:** ${item.competition_estimate}
- **Top competitor:** ${item.top_competitor}
- **Competitor gap:** ${item.competitor_gap}
- **Unique angle:** ${item.unique_angle}
- **Build difficulty:** ${item.difficulty}
- **Status:** ⬜ Not reviewed
`;
}

async function main() {
  if (!API_KEY) {
    console.error('GEMINI_API_KEY not set — aborting, no file written.');
    process.exit(1);
  }

  let ideas;
  try {
    ideas = await callGemini();
  } catch (err) {
    console.error('Research call failed:', err.message);
    process.exit(1);
  }

  // Filter out anything that accidentally matches an existing slug
  ideas = ideas.filter(i => !EXISTING_TOOLS.includes(i.slug));

  const dateStr = new Date().toISOString().split('T')[0];
  const header = `\n---\n\n## 🗓️ Research Run — ${dateStr}\n`;
  const body = ideas.map(formatEntry).join('\n');

  let existing = '';
  if (fs.existsSync(OUTPUT_FILE)) {
    existing = fs.readFileSync(OUTPUT_FILE, 'utf8');
  } else {
    existing = '# Toolyfi — New Tool Research Queue\n> Auto-generated by Gemini Research Agent. Review only — nothing here is auto-published.\n';
  }

  fs.writeFileSync(OUTPUT_FILE, existing + header + body);
  console.log(`Wrote ${ideas.length} new tool ideas to research-queue.md`);
}

main();
